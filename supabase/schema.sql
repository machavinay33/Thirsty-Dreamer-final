drop policy if exists "Public may read site media" on storage.objects;
drop policy if exists "Site admins may upload media" on storage.objects;
drop policy if exists "Site admins may update media" on storage.objects;
drop policy if exists "Site admins may delete media" on storage.objects;
create policy "Public may read site media" on storage.objects
  for select to anon, authenticated using (bucket_id = 'site-media');
create policy "Site admins may upload media" on storage.objects
  for insert to authenticated with check (bucket_id = 'site-media' and public.is_site_admin());
create policy "Site admins may update media" on storage.objects
  for update to authenticated using (bucket_id = 'site-media' and public.is_site_admin())
  with check (bucket_id = 'site-media' and public.is_site_admin());
create policy "Site admins may delete media" on storage.objects
  for delete to authenticated using (bucket_id = 'site-media' and public.is_site_admin());
