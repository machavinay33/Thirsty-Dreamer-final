insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'site-media',
  'site-media',
  true,
  52428800,
  array['video/mp4','video/webm','video/quicktime','image/jpeg','image/png','image/webp','image/avif']::text[]
